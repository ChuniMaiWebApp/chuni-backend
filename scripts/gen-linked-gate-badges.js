/**
 * Regenerates the Linked GATE badge lookup from chuni-penguin's consts.py.
 *
 * The badge filenames are 32-character hashes; transcribing 29 of them by hand
 * is a good way to introduce a silent typo, so they are extracted instead.
 *
 *   node scripts/gen-linked-gate-badges.js [path-to-consts.py]
 */
const { readFileSync, writeFileSync } = require('node:fs');
const { join } = require('node:path');

const source =
  process.argv[2] ??
  'D:/Code/chuni-penguin/chuni_penguin/adapters/chunithm_net/consts.py';

const python = readFileSync(source, 'utf8');

// "HASH": ( LinkedGate.name | None , LinkedGateStatus.name )
const ENTRY =
  /"([A-Z0-9]{32})"\s*:\s*\(\s*(?:LinkedGate\.(\w+)|None)\s*,\s*LinkedGateStatus\.(\w+)\s*,?\s*\)/g;

const STATUS = {
  not_found: 'NOT_FOUND',
  under_analysis: 'UNDER_ANALYSIS',
  linkable: 'LINKABLE',
  clear: 'CLEAR',
};

const entries = [];
let match;

while ((match = ENTRY.exec(python)) !== null) {
  const [, hash, gate, status] = match;

  if (!STATUS[status]) {
    throw new Error(`Unknown status "${status}" for ${hash}`);
  }

  entries.push({ hash, gate: gate ?? null, status: STATUS[status] });
}

if (entries.length === 0) {
  throw new Error('No badge entries found — has the source format changed?');
}

// Keys are always quoted: several hashes begin with a digit, which is not a
// valid bare property name.
const lines = entries
  .map(
    ({ hash, gate, status }) =>
      `  '${hash}': LinkedGateStatus.${status},` +
      (gate ? ` // ${gate}` : ' // any gate'),
  )
  .join('\n');

const output = `/**
 * Linked GATE progress badges, keyed by the image filename CHUNITHM-NET serves.
 *
 * Generated by scripts/gen-linked-gate-badges.js from chuni-penguin (0BSD).
 * Do not edit by hand — rerun the script when SEGA adds a gate.
 */
import { LinkedGateStatus } from './linked-verse';

export const LINKED_GATE_BADGES: Record<string, LinkedGateStatus> = {
${lines}
};
`;

const target = join(
  __dirname,
  '..',
  'src',
  'shared',
  'chunithm-net',
  'linked-gate-badges.ts',
);

writeFileSync(target, output, 'utf8');

console.log(`wrote ${entries.length} badges to ${target}`);
