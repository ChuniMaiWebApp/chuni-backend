/**
 * Regenerates src/shared/chunithm-net/parsing/special-titles.ts from
 * chuni-penguin's titles.json. Run when SEGA adds new collaboration titles:
 *
 *   node scripts/gen-special-titles.js <path-to-titles.json>
 */
const { readFileSync, writeFileSync } = require('node:fs');
const { join } = require('node:path');

const source =
  process.argv[2] ??
  'D:/Code/chuni-penguin/chuni_penguin/adapters/chunithm_net/assets/titles.json';

const data = JSON.parse(readFileSync(source, 'utf8'));
const target = join(
  __dirname,
  '..',
  'src',
  'shared',
  'chunithm-net',
  'parsing',
  'special-titles.ts',
);

const header = `/**
 * Collaboration titles whose text exists only inside the background image, so
 * they cannot be read out of the DOM like ordinary titles.
 *
 * Generated by scripts/gen-special-titles.js from chuni-penguin (0BSD).
 * Do not edit by hand.
 */
export const SPECIAL_TITLES: Record<
  string,
  { content: string; rarity: string }
> = `;

writeFileSync(target, `${header}${JSON.stringify(data, null, 2)};\n`, 'utf8');

console.log(`wrote ${Object.keys(data).length} titles to ${target}`);
